-- 1. TABLA: usuarios (docentes y estudiantes)
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL DEFAULT '123456',
    rol TEXT NOT NULL CHECK (rol IN ('docente', 'estudiante')),
    grado TEXT,
    telefono TEXT,
    creado_en TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. TABLA: cursos (asignaturas escolares)
CREATE TABLE IF NOT EXISTS cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    grado TEXT NOT NULL,
    docente_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    descripcion TEXT,
    progreso INTEGER DEFAULT 75,
    creado_en TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. TABLA: matriculas (asociación estudiante <-> curso)
CREATE TABLE IF NOT EXISTS matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    curso_id BIGINT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
    creado_en TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    UNIQUE(estudiante_id, curso_id)
);

-- 4. TABLA: actividades (talleres, quices, proyectos)
CREATE TABLE IF NOT EXISTS actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
    titulo TEXT NOT NULL,
    tipo TEXT DEFAULT 'Taller',
    fecha_entrega TEXT NOT NULL,
    estado TEXT DEFAULT 'Pendiente',
    creado_en TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 5. TABLA: calificaciones (registro de notas de 1.0 a 5.0)
CREATE TABLE IF NOT EXISTS calificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    curso_id BIGINT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
    actividad_id BIGINT REFERENCES actividades(id) ON DELETE SET NULL,
    actividad_nombre TEXT NOT NULL,
    nota NUMERIC(3, 1) NOT NULL CHECK (nota >= 0.0 AND nota <= 5.0),
    observacion TEXT,
    fecha TEXT NOT NULL,
    creado_en TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 6. TABLA: reportes_individuales (observaciones y reportes individuales para estudiantes)
CREATE TABLE IF NOT EXISTS reportes_individuales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    docente_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    curso_id BIGINT REFERENCES cursos(id) ON DELETE SET NULL,
    periodo TEXT DEFAULT 'Primer Periodo',
    tipo TEXT DEFAULT 'Seguimiento Académico',
    titulo TEXT NOT NULL,
    contenido TEXT NOT NULL,
    recomendaciones TEXT,
    fecha TEXT NOT NULL,
    archivo_adjunto TEXT,
    archivo_nombre TEXT,
    creado_en TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

