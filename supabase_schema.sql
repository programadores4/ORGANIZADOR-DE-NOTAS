DO $$
BEGIN
    DROP POLICY IF EXISTS "Permitir todo en usuarios" ON usuarios;
    CREATE POLICY "Permitir todo en usuarios" ON usuarios FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Permitir todo en cursos" ON cursos;
    CREATE POLICY "Permitir todo en cursos" ON cursos FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Permitir todo en matriculas" ON matriculas;
    CREATE POLICY "Permitir todo en matriculas" ON matriculas FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Permitir todo en actividades" ON actividades;
    CREATE POLICY "Permitir todo en actividades" ON actividades FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Permitir todo en calificaciones" ON calificaciones;
    CREATE POLICY "Permitir todo en calificaciones" ON calificaciones FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Permitir todo en reportes_individuales" ON reportes_individuales;
    CREATE POLICY "Permitir todo en reportes_individuales" ON reportes_individuales FOR ALL USING (true) WITH CHECK (true);
END $$;

